import fs from 'fs/promises';
import path from 'path';
import DatabaseService from '../src/services/databaseService';

function escapeSqlValue(value: any): string {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number' || typeof value === 'bigint') return value.toString();
  if (typeof value === 'boolean') return value ? '1' : '0';

  const escaped = value
    .toString()
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r');

  return `'${escaped}'`;
}

async function main() {
  const args = process.argv.slice(2);
  const outputArg = args.find(arg => arg.startsWith('--output='));
  const outputFile = outputArg?.split('=')[1];

  const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
  const backupDir = path.resolve(__dirname, '..', 'db_backups');
  const backupPath = outputFile
    ? path.resolve(outputFile)
    : path.join(backupDir, `idmegacentral_backup_${timestamp}.sql`);

  await fs.mkdir(path.dirname(backupPath), { recursive: true });

  console.log(`Création du backup SQL dans : ${backupPath}`);

  const header = `-- Backup SQL export generated by backend/scripts/backup_database.ts
-- Database: idmegacentral
-- Generated at: ${new Date().toISOString()}

SET FOREIGN_KEY_CHECKS=0;

`;

  await fs.writeFile(backupPath, header, 'utf8');

  const tablesResult = await DatabaseService.query("SHOW TABLES");
  const tableKey = Object.keys(tablesResult[0] || {})[0];
  const tables = tablesResult.map((row: any) => row[tableKey]);

  for (const table of tables) {
    console.log(`Backup table: ${table}`);
    const createRows = await DatabaseService.query(`SHOW CREATE TABLE \`${table}\``);
    const createSql = createRows[0]?.['Create Table'] || createRows[0]?.['Create View'] || '';
    if (!createSql) {
      throw new Error(`Impossible de récupérer la définition de la table ${table}`);
    }

    await fs.appendFile(backupPath, `DROP TABLE IF EXISTS \`${table}\`;
${createSql};

`, 'utf8');

    const rows: any[] = await DatabaseService.query(`SELECT * FROM \`${table}\``);
    if (rows.length === 0) {
      continue;
    }

    const columns = Object.keys(rows[0]).map(column => `\`${column}\``).join(', ');
    const batchSize = 200;
    for (let i = 0; i < rows.length; i += batchSize) {
      const batch = rows.slice(i, i + batchSize);
      const valuesSql = batch
        .map(row => {
          const values = Object.keys(row).map(column => escapeSqlValue(row[column]));
          return `(${values.join(', ')})`;
        })
        .join(',\n');

      await fs.appendFile(backupPath, `INSERT INTO \`${table}\` (${columns}) VALUES\n${valuesSql};
`, 'utf8');
    }

    await fs.appendFile(backupPath, '\n', 'utf8');
  }

  await fs.appendFile(backupPath, 'SET FOREIGN_KEY_CHECKS=1;\n', 'utf8');
  await DatabaseService.closePool();
  console.log('Backup terminé.');
}

main().catch(error => {
  console.error('Erreur lors de la sauvegarde de la base de données :', error);
  process.exit(1);
});
